"""Streamlit interface for the saved bank customer churn model."""

from pathlib import Path
import pickle
import sys

import numpy as np
import pandas as pd
import streamlit as st


ROOT = Path(__file__).resolve().parent
MODEL_PATH = ROOT / "churn_model.h5"
SCALER_PATH = ROOT / "scaler.pkl"
GENDER_ENCODER_PATH = ROOT / "label_encoder.pkl"
GEOGRAPHY_ENCODER_PATH = ROOT / "onehot_encoder.pkl"

st.set_page_config(
    page_title="Customer Churn Predictor",
    page_icon="📊",
    layout="wide",
)


@st.cache_resource(show_spinner="Loading the trained model…")
def load_artifacts():
    """Load the model and preprocessing artifacts once per app session."""
    missing = [
        path.name
        for path in (MODEL_PATH, SCALER_PATH, GENDER_ENCODER_PATH, GEOGRAPHY_ENCODER_PATH)
        if not path.is_file()
    ]
    if missing:
        raise FileNotFoundError("Missing required files: " + ", ".join(missing))

    # Import TensorFlow only when needed so a missing dependency has a useful message.
    from tensorflow.keras.models import load_model

    model = load_model(MODEL_PATH)
    with SCALER_PATH.open("rb") as file:
        scaler = pickle.load(file)
    with GENDER_ENCODER_PATH.open("rb") as file:
        gender_encoder = pickle.load(file)
    with GEOGRAPHY_ENCODER_PATH.open("rb") as file:
        geography_encoder = pickle.load(file)
    return model, scaler, gender_encoder, geography_encoder


def prepare_features(values, scaler, gender_encoder, geography_encoder):
    """Apply the same encoding and feature order used by experiments.ipynb."""
    gender_values = gender_encoder.transform([values["Gender"]])
    geography_values = geography_encoder.transform(pd.DataFrame({"Geography": [values["Geography"]]}))
    if hasattr(geography_values, "toarray"):
        geography_values = geography_values.toarray()

    base = {
        "CreditScore": values["CreditScore"],
        "Gender": int(gender_values[0]),
        "Age": values["Age"],
        "Tenure": values["Tenure"],
        "Balance": values["Balance"],
        "NumOfProducts": values["NumOfProducts"],
        "HasCrCard": values["HasCrCard"],
        "IsActiveMember": values["IsActiveMember"],
        "EstimatedSalary": values["EstimatedSalary"],
    }
    feature_row = pd.DataFrame([base])
    geography_columns = geography_encoder.get_feature_names_out(["Geography"])
    geography_frame = pd.DataFrame(geography_values, columns=geography_columns)
    feature_row = pd.concat([feature_row, geography_frame], axis=1)

    # Keep compatibility with scalers that recorded training column names.
    if hasattr(scaler, "feature_names_in_"):
        feature_row = feature_row.reindex(columns=scaler.feature_names_in_)
    if feature_row.shape[1] != scaler.n_features_in_:
        raise ValueError(
            f"Preprocessing produced {feature_row.shape[1]} features, but the saved "
            f"scaler expects {scaler.n_features_in_}. Check that the model and encoders "
            "were generated by the same notebook run."
        )
    return scaler.transform(feature_row)


st.title("Customer Churn Predictor")
st.write(
    "Estimate whether a bank customer is likely to leave using the trained neural network. "
    "Enter the customer profile, then select **Predict churn**."
)

with st.sidebar:
    st.header("Customer profile")
    with st.form("customer_profile"):
        left, right = st.columns(2)
        with left:
            credit_score = st.number_input("Credit score", min_value=300, max_value=900, value=650, step=1)
            age = st.number_input("Age", min_value=18, max_value=100, value=40, step=1)
            tenure = st.number_input("Tenure (years)", min_value=0, max_value=10, value=3, step=1)
            geography = st.selectbox("Geography", ["France", "Germany", "Spain"])
            gender = st.selectbox("Gender", ["Female", "Male"])
        with right:
            balance = st.number_input("Account balance", min_value=0.0, value=60000.0, step=1000.0, format="%.2f")
            products = st.selectbox("Number of products", [1, 2, 3, 4], index=1)
            has_card = st.selectbox("Has a credit card", ["Yes", "No"])
            active = st.selectbox("Is an active member", ["Yes", "No"])
            salary = st.number_input("Estimated salary", min_value=0.0, value=50000.0, step=1000.0, format="%.2f")
        submitted = st.form_submit_button("Predict churn", type="primary", use_container_width=True)

if submitted:
    profile = {
        "CreditScore": int(credit_score),
        "Geography": geography,
        "Gender": gender,
        "Age": int(age),
        "Tenure": int(tenure),
        "Balance": float(balance),
        "NumOfProducts": int(products),
        "HasCrCard": int(has_card == "Yes"),
        "IsActiveMember": int(active == "Yes"),
        "EstimatedSalary": float(salary),
    }
    try:
        model, scaler, gender_encoder, geography_encoder = load_artifacts()
        model_input = prepare_features(profile, scaler, gender_encoder, geography_encoder)
        probability = float(np.asarray(model.predict(model_input, verbose=0)).reshape(-1)[0])
        probability = min(max(probability, 0.0), 1.0)

        st.subheader("Prediction")
        result_col, probability_col = st.columns([1, 2])
        with result_col:
            if probability >= 0.5:
                st.error("Higher churn risk")
                st.write("The model estimates this customer is likely to leave.")
            else:
                st.success("Lower churn risk")
                st.write("The model estimates this customer is unlikely to leave.")
        with probability_col:
            st.metric("Estimated churn probability", f"{probability:.1%}")
            st.progress(probability, text="Churn probability")
        st.caption("The 50% cutoff is the model's classification threshold. This estimate is not a guarantee.")
    except FileNotFoundError as error:
        st.error(str(error))
        st.info("Run the training cells in `experiments.ipynb` first to create the model and preprocessing files.")
    except ModuleNotFoundError as error:
        if error.name and error.name.startswith("tensorflow"):
            st.error(
                "TensorFlow is not installed in the Python environment running this app "
                f"(`{sys.executable}`). From the project folder, start it with "
                "`venv\\python.exe -m streamlit run app.py` so Streamlit uses the "
                "project environment."
            )
        else:
            st.error(f"A required Python package is unavailable: {error}")
    except Exception as error:
        st.error(f"Could not create a prediction: {error}")
else:
    st.info("Fill in the customer profile in the sidebar and run a prediction.")

st.divider()
st.caption("Powered by the project's saved Keras model, encoders, and StandardScaler.")
